def run() -> set[str]:
    corpus = accept.Corpus()
    spec = accept.Spec(accept.SPEC_PATH)
    r = accept.Report()
    accept.check_spec(spec, corpus, r)
    # A 類：沒有回收檔時，只有不靠 out/ 的散文型斷言會跑（A15／A22 的停跑偵測）
    accept.check_prose_rules(spec, {}, corpus, r)
    return r.codes()


def main() -> int:
    original = SPEC.read_bytes()
    raw = original.decode("utf-8")

    base = run()
    if base:
        print(f"探針無法起跑：未毒化的 SPEC 本來就有 FAIL {sorted(base)}")
        return 1
    print("baseline: 0 FAIL\n")

    bad: list[str] = []
    try:
        for name, old, new, want in CASES:
            n = raw.count(old)
            if n != 1:
                bad.append(f"{name}：毒化目標在 SPEC 裡出現 {n} 次（探針過期或不唯一）")
                print(f"  SKIP {name} —— 目標出現 {n} 次")
                continue
            SPEC.write_bytes(raw.replace(old, new, 1).encode("utf-8"))
            got = run()
            if got == want:
                print(f"  OK   {name} -> {sorted(got)}")
            else:
                bad.append(f"{name}：預期 {sorted(want)}，實得 {sorted(got)}")
                print(f"  BAD  {name} —— 預期 {sorted(want)}，實得 {sorted(got)}")
    finally:
        SPEC.write_bytes(original)

    if SPEC.read_bytes() != original:
        print("\n還原失敗：SPEC.md 位元組與跑之前不同")
        return 1
    if run():
        print("\n還原後 SPEC 不是 0 FAIL——探針弄髒了檔案")
        return 1

    print(f"\n--- {len(CASES) - len(bad)}/{len(CASES)} 條毒化拿到預期的完整 FAIL 集合 ---")
    for b in bad:
        print("BAD " + b)
    return 1 if bad else 0


if __name__ == "__main__":
    sys.exit(main())
